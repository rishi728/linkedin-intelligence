// Runs after `next build`. Writes out/sw.js: a service worker that saves the app's own static files
// on the first visit, so NesT opens and runs with no internet afterwards.
//
// It only ever touches same-origin GET requests for the app's files. User data lives in IndexedDB and
// is never fetched, so it never passes through here.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = new URL("../out/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

// Boilerplate from the project template that the app never uses, and the share-preview image,
// which only link previews need.
const SKIP = new Set(["sw.js", "file.svg", "globe.svg", "next.svg", "vercel.svg", "window.svg", "og-image.jpg"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(OUT)
  .map((full) => ({ full, rel: relative(OUT, full).split(sep).join("/") }))
  .filter((f) => !SKIP.has(f.rel))
  .sort((a, b) => a.rel.localeCompare(b.rel));

const urlOf = (rel) => {
  if (rel === "index.html") return "/";
  if (rel.endsWith("/index.html")) return `/${rel.slice(0, -"index.html".length)}`;
  return `/${rel}`;
};

const urls = files.map((f) => urlOf(f.rel));
const hash = createHash("sha256");
for (const f of files) hash.update(f.rel).update(readFileSync(f.full));
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/make-sw.mjs. Do not edit.
const CACHE = "nest-${version}";
const ASSETS = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("nest-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname === "/sw.js") return;

  // Pages: ask the network first so a new deploy shows up, and fall back to the saved copy offline.
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
          return res;
        })
        .catch(() => caches.match(req, { ignoreSearch: true }).then((hit) => hit || caches.match("/404.html"))),
    );
    return;
  }

  // Everything else (scripts, styles, fonts, images, page data): the saved copy first. The ?_rsc
  // part of page-data requests changes, so it is ignored when matching.
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) => hit || fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      }),
    ),
  );
});
`;

writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js written: ${urls.length} files, version ${version}`);
